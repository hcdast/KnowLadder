import { mkdir, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL(
  process.env.OPENAPI_URL ?? "http://127.0.0.1:3000/api/openapi.json",
);
const output = new URL("../src/api/schema.d.ts", import.meta.url);
const schema = await openapiTS(source);
const contents = `// Generated by npm run generate:api. Do not edit manually.\n${astToString(schema)}`;
await mkdir(new URL("./", output), { recursive: true });
await writeFile(output, contents, "utf8");
console.log("已从 OpenAPI 生成 src/api/schema.d.ts");
